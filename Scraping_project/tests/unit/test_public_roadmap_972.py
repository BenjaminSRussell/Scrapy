"""Public roadmap page is generated from open [P1]–[P4] titles (#972)."""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest
import yaml

PROJECT = Path(__file__).resolve().parents[2]
REPO = PROJECT.parent
SCRIPT = PROJECT / "scripts" / "generate_public_roadmap.py"
PAGE = REPO / "docs" / "PUBLIC_ROADMAP.md"
WORKFLOW = REPO / ".github" / "workflows" / "ci-public-roadmap.yml"


def _load():
    spec = importlib.util.spec_from_file_location("generate_public_roadmap", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _issue(number, title, state="open", url=None, pull_request=None):
    item = {
        "number": number,
        "title": title,
        "state": state,
        "html_url": url or f"https://github.com/BenjaminSRussell/scrapy/issues/{number}",
    }
    if pull_request is not None:
        item["pull_request"] = pull_request
    return item


@pytest.fixture(scope="module")
def roadmap():
    return _load()


@pytest.mark.unit
def test_groups_open_prefixed_titles_and_skips_the_rest(roadmap):
    issues = [
        _issue(30, "[P2] second"),
        _issue(10, "[P1] first"),
        _issue(11, "[P1] later"),
        _issue(40, "[P4] much later"),
        _issue(20, "[P3] third"),
        _issue(99, "[P10] not a phase"),
        _issue(98, "note [P1] in the middle"),
        _issue(97, "[P1] closed already", state="closed"),
        _issue(96, "[P1] this is a pull request", pull_request={"url": "https://example.invalid"}),
        _issue(12, "[p1] wrong case"),
    ]
    grouped = roadmap.select_issues(issues)
    assert [item["number"] for item in grouped["1"]] == [10, 11]
    assert [item["number"] for item in grouped["2"]] == [30]
    assert [item["number"] for item in grouped["3"]] == [20]
    assert [item["number"] for item in grouped["4"]] == [40]


@pytest.mark.unit
def test_render_escapes_titles_and_keeps_phase_order(roadmap):
    text = roadmap.render(
        [
            _issue(4, "[P4] see [docs](https://evil.example) <script>"),
            _issue(2, "[P2] keep `ticks`"),
        ],
        repo="BenjaminSRussell/scrapy",
        generated_at="2026-10-14T00:00:00Z",
    )
    assert text.index("## P1") < text.index("## P2") < text.index("## P3") < text.index("## P4")
    assert "_None open._" in text
    assert "](https://evil.example)" not in text
    assert r"\[docs\]&#40;https://evil.example&#41;" in text
    assert "<script>" not in text
    assert "&lt;script&gt;" in text
    assert "`ticks`" not in text
    assert "keep 'ticks'" in text
    assert "Open items: 2" in text
    assert "Generated: 2026-10-14T00:00:00Z" in text


@pytest.mark.unit
def test_publish_skips_timestamp_only_rewrites(roadmap, tmp_path):
    issues = [_issue(1, "[P1] only")]
    path = tmp_path / "PUBLIC_ROADMAP.md"
    first = roadmap.render(issues, repo="BenjaminSRussell/scrapy", generated_at="2026-10-14T00:00:00Z")
    assert roadmap.publish(path, first) is True
    second = roadmap.render(issues, repo="BenjaminSRussell/scrapy", generated_at="2026-10-21T06:17:00Z")
    assert roadmap.publish(path, second) is False
    assert path.read_text(encoding="utf-8") == first
    changed = roadmap.render(
        [_issue(1, "[P1] only"), _issue(2, "[P1] added")],
        repo="BenjaminSRussell/scrapy",
        generated_at="2026-10-21T06:17:00Z",
    )
    assert roadmap.publish(path, changed) is True
    assert "Open items: 2" in path.read_text(encoding="utf-8")


@pytest.mark.unit
def test_fetch_refuses_a_repo_that_could_change_the_host(roadmap):
    with pytest.raises(roadmap.RoadmapError):
        roadmap.fetch_open_issues("BenjaminSRussell/scrapy?x=1", None)
    with pytest.raises(roadmap.RoadmapError):
        roadmap._request("https://example.invalid/repos", None)
    with pytest.raises(roadmap.RoadmapError, match="redirected"):
        roadmap._NoRedirect().redirect_request(None, None, 302, "moved", {}, "https://evil.example")


@pytest.mark.unit
def test_published_page_lists_real_prefixed_issues():
    text = PAGE.read_text(encoding="utf-8")
    assert text.startswith(
        "<!-- generated by Scraping_project/scripts/generate_public_roadmap.py; do not edit -->"
    )
    assert "## P1" in text and "## P2" in text and "## P3" in text and "## P4" in text
    items = re.findall(
        r"^- \[#(\d+)\]\(https://github.com/[^)]+/issues/(\d+)\) \\\[P[1-4]\\\]",
        text,
        re.M,
    )
    count = int(re.search(r"^Open items: (\d+)$", text, re.M).group(1))
    assert count == len(items)
    assert count > 0
    assert all(number == url_number for number, url_number in items)


@pytest.mark.unit
def test_weekly_workflow_refreshes_from_main_only():
    text = WORKFLOW.read_text(encoding="utf-8")
    doc = yaml.safe_load(text)
    trigger = doc[True]
    assert trigger["schedule"] == [{"cron": "17 6 * * 1"}]
    assert "workflow_dispatch" in trigger
    assert "push" not in trigger
    assert "pull_request" not in trigger
    job = doc["jobs"]["refresh"]
    assert job["timeout-minutes"] == 10
    assert job["permissions"]["contents"] == "write"
    assert job["permissions"]["issues"] == "read"
    assert "github.ref == 'refs/heads/main'" in text
    assert "docs/PUBLIC_ROADMAP.md" in text
    assert "git push origin HEAD:main" in text
    assert "Scraping_project/scripts/generate_public_roadmap.py" in text
