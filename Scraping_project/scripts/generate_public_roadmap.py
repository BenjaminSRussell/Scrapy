#!/usr/bin/env python3
"""Write docs/PUBLIC_ROADMAP.md from open issues titled [P1]–[P4].

Stdlib only. Does not crawl, import the pipeline, or read a lake.
Pass ``--input`` with a JSON list to render offline. With no ``--input``,
the script reads open issues from the GitHub REST API (``GITHUB_TOKEN`` or
``GH_TOKEN`` when set). A weekly run that sees the same backlog leaves the
file untouched so the timestamp does not churn.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = REPO_ROOT / "docs" / "PUBLIC_ROADMAP.md"
DEFAULT_REPO = "BenjaminSRussell/scrapy"
API = "https://api.github.com"
MAX_PAGES = 50

# [P10] must not match: the closing bracket has to follow the single digit.
TITLE_RE = re.compile(r"^\[P([1-4])\](.*)$")
REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
STAMP_RE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$")
GENERATED_LINE = re.compile(r"^Generated: .*$", re.MULTILINE)

PHASES = (
    ("1", "P1", "Correctness and trustworthy glass"),
    ("2", "P2", "Reliability and the same-origin shell"),
    ("3", "P3", "Operable pipeline"),
    ("4", "P4", "Scale and finish"),
)


class RoadmapError(RuntimeError):
    """The page was not written because the input or the API was unusable."""


def escape_title(title: str) -> str:
    """One markdown line: no raw links, HTML, or line breaks from a title."""
    text = " ".join(str(title).split())
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("`", "'")
        .replace("[", "\\[")
        .replace("]", "\\]")
        .replace("(", "&#40;")
        .replace(")", "&#41;")
    )


def select_issues(issues: list[dict]) -> dict[str, list[dict]]:
    """Group open, non-PR issues by the [P1]–[P4] title prefix."""
    grouped: dict[str, list[dict]] = {key: [] for key, _, _ in PHASES}
    for issue in issues:
        if not isinstance(issue, dict) or issue.get("pull_request"):
            continue
        state = issue.get("state")
        if state is not None and state != "open":
            continue
        title = issue.get("title")
        number = issue.get("number")
        if not isinstance(title, str) or not isinstance(number, int):
            continue
        match = TITLE_RE.match(title.strip())
        if match is None:
            continue
        grouped[match.group(1)].append(issue)
    for rows in grouped.values():
        rows.sort(key=lambda item: item["number"])
    return grouped


def _issue_url(issue: dict, repo: str) -> str:
    url = issue.get("html_url")
    fallback = f"https://github.com/{repo}/issues/{issue['number']}"
    if not isinstance(url, str) or not url.startswith("https://github.com/"):
        return fallback
    return url


def render(issues: list[dict], *, repo: str, generated_at: str) -> str:
    grouped = select_issues(issues)
    total = sum(len(rows) for rows in grouped.values())
    lines = [
        "<!-- generated by Scraping_project/scripts/generate_public_roadmap.py; do not edit -->",
        "# Public roadmap",
        "",
        "Open GitHub issues whose titles start with `[P1]`, `[P2]`, `[P3]`, or `[P4]`.",
        "The build order stays in [ROADMAP.md](ROADMAP.md). This page is only the live backlog.",
        "",
        f"Generated: {generated_at}",
        f"Open items: {total}",
        "",
        f"Tracker: <https://github.com/{repo}/issues>",
        "",
    ]
    for key, label, blurb in PHASES:
        rows = grouped[key]
        lines.append(f"## {label}")
        lines.append("")
        lines.append(f"{blurb}.")
        lines.append("")
        if not rows:
            lines.append("_None open._")
            lines.append("")
            continue
        lines.append(f"{len(rows)} open.")
        lines.append("")
        for issue in rows:
            url = _issue_url(issue, repo)
            lines.append(f"- [#{issue['number']}]({url}) {escape_title(issue['title'])}")
        lines.append("")
    lines.append(
        "Refreshed weekly by `.github/workflows/ci-public-roadmap.yml` "
        "(Monday 06:17 UTC) and on demand via workflow_dispatch."
    )
    lines.append("")
    return "\n".join(lines)


def publish(path: Path, text: str) -> bool:
    """Write ``text`` unless the backlog matches the file already on disk.

    Returns True when the file changed. The generated timestamp is ignored,
    so a weekly run with the same issues does not rewrite the page.
    """
    if path.is_file():
        old = path.read_text(encoding="utf-8")
        if GENERATED_LINE.sub("Generated: STAMP", old) == GENERATED_LINE.sub("Generated: STAMP", text):
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def _next_link(header: str | None) -> str | None:
    if not header:
        return None
    for part in header.split(","):
        bits = [bit.strip() for bit in part.split(";")]
        if len(bits) >= 2 and bits[1] == 'rel="next"':
            url = bits[0].strip("<>")
            if not url.startswith(f"{API}/"):
                raise RoadmapError("refusing next-page URL outside api.github.com")
            return url
    return None


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    """Do not follow redirects. The token must not leave api.github.com."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise RoadmapError(f"GitHub API redirected ({code})")


def _request(url: str, token: str | None) -> tuple[object, str | None]:
    if not url.startswith(f"{API}/"):
        raise RoadmapError("refusing non-API URL")
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "scrapy-public-roadmap",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    opener = urllib.request.build_opener(_NoRedirect)
    try:
        with opener.open(request, timeout=30) as response:
            payload = json.loads(response.read().decode("utf-8"))
            nxt = _next_link(response.headers.get("Link"))
    except urllib.error.HTTPError as exc:
        raise RoadmapError(f"GitHub API HTTP {exc.code}") from exc
    except urllib.error.URLError as exc:
        raise RoadmapError(f"GitHub API request failed: {exc.reason}") from exc
    return payload, nxt


def fetch_open_issues(repo: str, token: str | None) -> list[dict]:
    if not REPO_RE.fullmatch(repo):
        raise RoadmapError(f"repo must be owner/name, got {repo!r}")
    url: str | None = f"{API}/repos/{repo}/issues?state=open&per_page=100"
    found: list[dict] = []
    for _ in range(MAX_PAGES):
        if url is None:
            return found
        payload, url = _request(url, token)
        if not isinstance(payload, list):
            raise RoadmapError("issues response was not a list")
        found.extend(item for item in payload if isinstance(item, dict))
        if url is None:
            return found
    raise RoadmapError(f"stopped after {MAX_PAGES} pages")


def _stamp(value: str | None) -> str:
    if value is None:
        return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if not STAMP_RE.fullmatch(value):
        raise RoadmapError("--now must be YYYY-MM-DDTHH:MM:SSZ")
    return value


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/PUBLIC_ROADMAP.md from open [P1]–[P4] issues.")
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", DEFAULT_REPO))
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--input", type=Path, help="Offline JSON list of issue objects")
    parser.add_argument("--now", default=None, help="UTC timestamp YYYY-MM-DDTHH:MM:SSZ")
    args = parser.parse_args(argv)
    if not REPO_RE.fullmatch(args.repo):
        print(f"repo must be owner/name, got {args.repo!r}", file=sys.stderr)
        return 2
    try:
        stamp = _stamp(args.now)
        if args.input is not None:
            raw = json.loads(args.input.read_text(encoding="utf-8"))
            if not isinstance(raw, list):
                print("input JSON must be a list", file=sys.stderr)
                return 2
            issues = raw
        else:
            token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN") or None
            if token is not None and not token.strip():
                token = None
            issues = fetch_open_issues(args.repo, token)
        text = render(issues, repo=args.repo, generated_at=stamp)
    except (OSError, json.JSONDecodeError, RoadmapError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    wrote = publish(args.output, text)
    print(f"{'wrote' if wrote else 'unchanged'} {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
